    async def perform_maintenance_task(self, task_type: MaintenanceTask,
                                     target_component: str = None) -> MaintenanceReport:
        """
        Perform a maintenance task using Gemini AI.

        Args:
            task_type: Type of maintenance task
            target_component: Specific component to maintain (optional)

        Returns:
            MaintenanceReport with findings and recommendations
        """

        report_id = str(uuid.uuid4())

        # Gather relevant data based on task type
        context_data = await self._gather_maintenance_context(task_type, target_component)

        # Generate maintenance analysis using Gemini
        analysis = await self._generate_maintenance_analysis(task_type, context_data)

        # Create actionable recommendations
        recommendations = await self._generate_recommendations(analysis, task_type)

        # Identify automated actions if applicable
        automated_actions = self._identify_automated_actions(recommendations, task_type)

        report = MaintenanceReport(
            report_id=report_id,
            task_type=task_type,
            target_component=target_component or "system_wide",
            generated_at=time.time(),
            findings=analysis.get("findings", []),
            recommendations=recommendations,
            priority_level=analysis.get("priority", "medium"),
            estimated_effort=analysis.get("effort", "moderate"),
            automated_actions=automated_actions
        )

        self.maintenance_reports.append(report)
        return report

    async def _gather_maintenance_context(self, task_type: MaintenanceTask,
                                        target_component: str = None) -> Dict[str, Any]:
        """Gather context data for maintenance analysis."""

        context = {
            "task_type": task_type.value,
            "timestamp": time.time(),
            "system_info": self._get_system_info()
        }

        if task_type == MaintenanceTask.SYSTEM_HEALTH_CHECK:
            context["components"] = self._get_component_health_data()
            context["performance_metrics"] = self._get_performance_metrics()

        elif task_type == MaintenanceTask.TOOL_LIFECYCLE_MANAGEMENT:
            context["tools"] = self._get_tool_status_data()
            context["usage_patterns"] = self._get_tool_usage_patterns()

        elif task_type == MaintenanceTask.PERFORMANCE_OPTIMIZATION:
            context["performance_data"] = self._get_detailed_performance_data()
            context["bottlenecks"] = self._identify_performance_bottlenecks()

        elif task_type == MaintenanceTask.SECURITY_AUDIT:
            context["security_data"] = self._get_security_audit_data()
            context["vulnerabilities"] = self._scan_for_vulnerabilities()

        elif task_type == MaintenanceTask.DOCUMENTATION_UPDATE:
            context["documentation_status"] = self._get_documentation_status()
            context["outdated_guides"] = self._identify_outdated_guides()

        if target_component:
            context["target_component"] = self._get_component_data(target_component)

        return context

    async def _generate_maintenance_analysis(self, task_type: MaintenanceTask,
                                           context: Dict[str, Any]) -> Dict[str, Any]:
        """Generate maintenance analysis using Gemini."""

        if not self.model:
            return self._generate_fallback_analysis(task_type, context)

        # Create analysis prompt based on task type
        prompt = self._create_maintenance_prompt(task_type, context)

        try:
            response = self.model.generate_content(prompt)
            analysis_text = response.text

            # Parse the analysis (assuming structured JSON response)
            try:
                analysis = json.loads(analysis_text)
            except json.JSONDecodeError:
                # Fallback to text parsing
                analysis = self._parse_analysis_text(analysis_text)

            return analysis

        except Exception as e:
            logger.error(f"Gemini analysis failed: {e}")
            return self._generate_fallback_analysis(task_type, context)

