    async def _batch_performance_analysis(self, targets: List[Dict[str, Any]]) -> List[Dict[str, Any]]:
        """Perform batch performance analysis."""

        results = []
        for target in targets:
            target_id = target.get("target_id")
            analysis_type = target.get("analysis_type", "general")

            # Perform performance analysis
            analysis = await self._analyze_performance(target_id, analysis_type)

            results.append({
                "target_id": target_id,
                "analysis_type": analysis_type,
                "metrics": analysis.get("metrics", {}),
                "bottlenecks": analysis.get("bottlenecks", []),
                "recommendations": analysis.get("recommendations", []),
                "score": analysis.get("performance_score", 0.0)
            })

        return results

