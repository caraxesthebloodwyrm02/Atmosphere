        """Get current session status."""

        if session_id not in self.active_sessions:
            return None

        session = self.active_sessions[session_id]

        return {
            "session_id": session_id,
            "user_id": session.user_id,
            "game_state": session.game_state.value,
            "current_challenge": session.current_challenge.title if session.current_challenge else None,
            "score": session.score,
            "level": session.level,
            "achievements": session.achievements,
            "claude_interactions": len(session.claude_interactions),
            "time_elapsed": time.time() - session.start_time
        }

