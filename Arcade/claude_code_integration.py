    def _extract_code_suggestions(self, response: str) -> List[str]:
        """Extract code suggestions from Claude response."""
        suggestions = []
        lines = response.split('\n')

        in_code_block = False
        current_code = []

        for line in lines:
            if line.strip().startswith('```'):
                if in_code_block:
                    if current_code:
                        suggestions.append('\n'.join(current_code))
                        current_code = []
                    in_code_block = False
                else:
                    in_code_block = True
            elif in_code_block:
                current_code.append(line)

        return suggestions

    def _extract_explanations(self, response: str) -> List[str]:
        """Extract explanations from Claude response."""
        # Simple extraction - look for bullet points or numbered lists
        explanations = []
        lines = response.split('\n')

        for line in lines:
            line = line.strip()
            if line.startswith(('•', '-', '*')) or (line[0].isdigit() and line[1:3] in ['. ', ') ']):
                explanations.append(line)

        return explanations

    def _extract_next_steps(self, response: str) -> List[str]:
        """Extract next steps from Claude response."""
        # Look for action-oriented language
        next_steps = []
        lines = response.split('\n')

        action_keywords = ['try', 'implement', 'create', 'add', 'modify', 'test', 'run', 'check']

        for line in lines:
            line_lower = line.lower()
            if any(keyword in line_lower for keyword in action_keywords):
                next_steps.append(line.strip())

        return next_steps[:5]  # Limit to 5 suggestions

    def _check_achievements(self, session: ClaudeCodingSession,
                          evaluation: Dict[str, Any]) -> List[str]:
        """Check for new achievements based on performance."""

        new_achievements = []

        # Speed achievement
        if evaluation.get("time_taken", 0) < 600:  # Under 10 minutes
            new_achievements.append("Speed Coder")

        # Quality achievement
        if evaluation.get("code_quality_score", 0) > 9.0:
            new_achievements.append("Code Quality Master")

        # Perfect solution
        if evaluation.get("score", 0) == 100:
            new_achievements.append("Perfect Solution")

        # Hint master (solved without hints)
        if evaluation.get("hints_used", 1) == 0:
            new_achievements.append("Hint Master")

        # Streak achievements
        if len(session.achievements) >= 5:
            new_achievements.append("Consistent Learner")

        return new_achievements

    def _update_user_progress(self, user_id: str, challenge: CodingChallenge,
                            evaluation: Dict[str, Any]):
        """Update user progress and statistics."""

        progress = self.user_progress[user_id]

        # Update completed challenges
        if challenge.challenge_id not in progress["completed_challenges"]:
            progress["completed_challenges"].append(challenge.challenge_id)

        # Update score
        progress["total_score"] += evaluation.get("score", 0)

        # Level up logic (simplified)
        if len(progress["completed_challenges"]) % 10 == 0:
            progress["level"] += 1

        # Update skills
        challenge_skills = challenge.learning_objectives
        for skill in challenge_skills:
            if skill not in progress["skills_mastered"]:
                progress["skills_mastered"].append(skill)

