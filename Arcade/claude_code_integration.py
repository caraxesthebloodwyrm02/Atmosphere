    async def get_claude_assistance(self, session_id: str, user_query: str,
                                  code_context: str = "") -> ClaudeResponse:
        """Get coding assistance from Claude."""

        if session_id not in self.active_sessions:
            return ClaudeResponse(
                response_type="error",
                content="Session not found"
            )

        session = self.active_sessions[session_id]

        # Build context for Claude
        context = f"""
        User is working on a coding challenge in session {session_id}.
        Current level: {session.level}
        Current score: {session.score}
        Active challenge: {session.current_challenge.title if session.current_challenge else 'None'}

        User query: {user_query}
        """

        if code_context:
            context += f"\n\nCurrent code:\n{code_context}"

        # Query Grokipedia for relevant knowledge
        grokipedia_results = await grokipedia.query(user_query, max_results=2)
        if grokipedia_results.entries:
            context += f"\n\nRelevant knowledge from Grokipedia:\n"
            for entry in grokipedia_results.entries[:2]:
                context += f"- {entry.title}: {entry.content[:200]}...\n"

        # Generate Claude response
        response_content = await self._generate_claude_response(context, user_query)

        # Parse response for structured output
        code_suggestions = self._extract_code_suggestions(response_content)
        explanations = self._extract_explanations(response_content)
        next_steps = self._extract_next_steps(response_content)

        # Record interaction
        session.claude_interactions.append({
            "timestamp": time.time(),
            "query": user_query,
            "response": response_content,
            "code_context": code_context
        })

        return ClaudeResponse(
            response_type="assistance",
            content=response_content,
            code_suggestions=code_suggestions,
            explanations=explanations,
            next_steps=next_steps,
            confidence_score=0.9
        )

