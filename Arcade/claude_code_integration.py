    async def submit_code_solution(self, session_id: str, code: str) -> Dict[str, Any]:
        """Submit code solution for evaluation."""

        if session_id not in self.active_sessions:
            return {"error": "Session not found"}

        session = self.active_sessions[session_id]

        if not session.current_challenge:
            return {"error": "No active challenge"}

        # Record submission in history
        session.code_history.append({
            "timestamp": time.time(),
            "code": code,
            "challenge_id": session.current_challenge.challenge_id
        })

        # Evaluate solution using Claude
        evaluation = await self._evaluate_solution_with_claude(session.current_challenge, code)

        # Update score and progress
        if evaluation.get("passed", False):
            points_earned = session.current_challenge.points_value
            session.score += points_earned

            # Check for achievements
            new_achievements = self._check_achievements(session, evaluation)
            session.achievements.extend(new_achievements)

            # Update user progress
            self._update_user_progress(session.user_id, session.current_challenge, evaluation)

        return {
            "passed": evaluation.get("passed", False),
            "score": evaluation.get("score", 0),
            "feedback": evaluation.get("feedback", ""),
            "hints_used": evaluation.get("hints_used", 0),
            "time_taken": evaluation.get("time_taken", 0),
            "new_achievements": new_achievements if 'new_achievements' in locals() else []
        }

